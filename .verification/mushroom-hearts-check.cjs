const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
global.window = global;
const root = path.resolve(__dirname, '..');
for (const file of ['js/app.js', 'js/config/gameConfig.js', 'js/renderers/MushroomDecorRenderer.js']) {
  vm.runInThisContext(fs.readFileSync(path.join(root, file), 'utf8'), { filename: file });
}
const system = new GameApp.renderers.MushroomDecorRenderer();
const platforms = [400, 300, 200, 100].map(y => ({ x: 100, y, width: 300 }));
system.configure(platforms, [], 1);
assert.deepEqual(system.mushrooms.map(m => m.timer), [29, 26, 23, 20]);
const player = { position: { x: -1000, y: -1000 }, width: 42, height: 42, health: 40, maxHealth: 100, get centerX() { return this.position.x + this.width / 2; } };
const advance = seconds => { for (let i = 0; i < Math.round(seconds * 60); i++) system.update(1 / 60, player); };
advance(20);
assert.deepEqual(system.mushrooms.map(m => !!m.heart), [false, false, false, true]);
assert.equal(system.mushrooms[3].timer, null);
assert.ok(system.mushrooms[3].spawnPulse > 0);
advance(3);
assert.deepEqual(system.mushrooms.map(m => !!m.heart), [false, false, true, true]);
advance(6);
assert.ok(system.mushrooms.every(m => m.heart));
const hearts = system.mushrooms.map(m => m.heart);
advance(50);
assert.ok(system.mushrooms.every((m, i) => m.heart === hearts[i] && m.timer === null && m.heart.landed));
const highest = system.mushrooms[3];
player.position = { x: highest.x + highest.heart.x - 21, y: highest.y + highest.heart.y - 21 };
system.update(0, player);
assert.equal(player.health, 70);
assert.equal(highest.heart, null);
assert.equal(highest.timer, GameApp.config.game.mushroomHearts.interval);
assert.equal(system.pickups.length, 1);
system.configure(platforms, [], 2);
assert.equal(highest.timer, 20);
assert.equal(system.mushrooms[3].timer, 20);
player.position = { x: -1000, y: -1000 };
advance(19);
assert.equal(system.mushrooms[3].heart, null);
advance(1);
assert.ok(system.mushrooms[3].heart);
advance(2);
const next = system.mushrooms[3];
player.health = 95;
player.position = { x: next.x + next.heart.x * 2 - 21, y: next.y + next.heart.y * 2 - 21 };
system.update(0, player);
assert.equal(player.health, 100);
assert.equal(next.timer, 20);
assert.ok(system.mushrooms.slice(0, 3).every((m, i) => m.heart === hearts[i]));
console.log('Mushroom hearts: initial stagger, single waiting heart, pickup healing, full cooldown reset, resize preservation and health cap passed.');
